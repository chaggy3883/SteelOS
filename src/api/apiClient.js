// Each API is built on first use, not when this file loads: building one
// reads its records from the database, and the database (IndexedDB, see
// dbPersistence.js) is only loaded once main.jsx has initialized it — after
// every module, this one included, has been imported.
const lazy = (factory) => {
  let api = null;
  return new Proxy({}, {
    get: (_, prop) => {
      if (!api) api = factory();
      const value = api[prop];
      return typeof value === 'function' ? value.bind(api) : value;
    },
    has: (_, prop) => { if (!api) api = factory(); return prop in api; },
  });
};
